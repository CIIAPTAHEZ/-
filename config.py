"""
Конфигурация приложения «Анализ рекламаций и операционного контроля».
При упаковке через PyInstaller рабочие папки создаются рядом с исполняемым файлом.
"""
import os
import sys
from pathlib import Path


def _get_base_dir() -> Path:
    """Определяет корневую папку приложения.

    В упакованном приложении (PyInstaller) используется папка, где находится
    исполняемый файл, чтобы данные (БД, копии, документы) хранились рядом.
    """
    if getattr(sys, "frozen", False):
        # Упакованное приложение: папка с exe
        return Path(sys.executable).resolve().parent
    # Исходный код: папка проекта
    return Path(__file__).resolve().parent


# Базовая директория проекта
BASE_DIR = _get_base_dir()

# Путь к файлу базы данных SQLite
DB_PATH = BASE_DIR / "data" / "claims.db"

# Папка для резервных копий БД
BACKUP_DIR = BASE_DIR / "data" / "backups"

# Папка для экспортированных отчётов
EXPORT_DIR = BASE_DIR / "exports"

# Корневая папка для хранения документов по претензиям.
# По умолчанию - локальная папка claims_files в директории проекта.
# В рабочей среде можно указать сетевой путь, например r"\\\\server\\claims"
CLAIMS_ROOT = BASE_DIR / "claims_files"

# Список форм изделий для модуля «Микролифт» (время опускания).
# Используется ТОЛЬКО при первом создании таблицы форм в БД — как
# стартовый набор из 21 позиции. Далее пользователь может самостоятельно
# переименовывать формы, добавлять новые или удалять их через интерфейс
# «Управление формами» (без перекомпиляции приложения).
MICROLIFT_FORMS = [f"Форма {i:02d}" for i in range(1, 22)]

# Типы замеров времени опускания микролифта.
# Ключ хранится в БД (столбец measure_type), значение — название в интерфейсе.
# Порядок ключей = порядок отображения в селекторе и в сводной таблице.
MEASURE_TYPES = {
    "seat": "Опускание сиденья",
    "lid": "Опускание крышки",
    "whole": "Опускание целого изделия",
}


def ensure_directories() -> None:
    """Создаёт необходимые директории при первом запуске."""
    for path in (DB_PATH.parent, BACKUP_DIR, EXPORT_DIR, CLAIMS_ROOT):
        path.mkdir(parents=True, exist_ok=True)
